#!/usr/bin/env node
/**
 * openapi.json から Operation 名 → { path, method } のマッピングを生成する。
 * 出力: src/operation-map.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const rootDir = resolve(__dirname, '..');

const spec = JSON.parse(readFileSync(resolve(rootDir, 'src/__generated__/openapi.json'), 'utf-8'));

const entries = [];

for (const [path, methods] of Object.entries(spec.paths ?? {})) {
  for (const [method, operation] of Object.entries(methods)) {
    if (!operation.operationId) continue;
    entries.push({ operationId: operation.operationId, path, method });
  }
}

// sort for stable output
entries.sort((a, b) => a.operationId.localeCompare(b.operationId));

const lines = [
  '/**',
  ' * This file was auto-generated by scripts/generate-operation-map.mjs',
  ' * Do not make direct changes to the file.',
  ' */',
  '',
  '/** Runtime mapping: Operation name → { path, method } */',
  'export const OPERATION_MAP = {',
];

for (const { operationId, path, method } of entries) {
  lines.push(`  ${operationId}: { path: '${path}', method: '${method}' },`);
}

lines.push('} as const;');
lines.push('');
lines.push('export type OperationMap = typeof OPERATION_MAP;');
lines.push('');

writeFileSync(resolve(rootDir, 'src/__generated__/operation-map.ts'), lines.join('\n'), 'utf-8');

console.log(`✅ Generated src/__generated__/operation-map.ts (${entries.length} operations)`);
